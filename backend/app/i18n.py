def current_language() -> str:
    return g.get("lang", DEFAULT_LANGUAGE)


def t(key: str, **kwargs) -> str:
    """Translate a UI string into the current language."""
    return t_in(current_language(), key, **kwargs)


def t_in(lang: str | None, key: str, **kwargs) -> str:
    """Translate into a given language, e.g. the customer's for an e-mail sent by the admin."""
    lang = lang if lang in LANGUAGES else DEFAULT_LANGUAGE
    text = TEXTS[lang].get(key) or TEXTS[DEFAULT_LANGUAGE].get(key, key)
    kwargs = {k: format_date(v, lang) if isinstance(v, date) else v for k, v in kwargs.items()}
    return text.format(**kwargs) if kwargs else text


def _native(value):
    """neo4j.time.Date/DateTime -> datetime.date/datetime."""
    return value.to_native() if hasattr(value, "to_native") else value


def format_date(value, lang: str | None = None) -> str:
    d = _native(value)
    if d is None:
        return ""
    if (lang or current_language()) == "en":
        return f"{d.day} {MONTHS_EN[d.month - 1]} {d.year}"
    return d.strftime("%d.%m.%Y")


def format_datetime(value) -> str:
    """Date and time in Norwegian time."""
    dt = _native(value)
    if dt is None:
        return ""
    if isinstance(dt, datetime) and dt.tzinfo:
        dt = dt.astimezone(TIMEZONE)
    return f"{format_date(dt)} {dt:%H:%M}"


def tr(obj: dict, field: str) -> str:
    """Pick obj[field_no] or obj[field_en], falling back to Norwegian."""
    return obj.get(f"{field}_{current_language()}") or obj.get(f"{field}_{DEFAULT_LANGUAGE}") or ""


def init_app(app: Flask) -> None:
    @app.before_request
    def set_language():
        g.lang = session.get("lang") if session.get("lang") in LANGUAGES else DEFAULT_LANGUAGE
        # The <html lang> attribute uses "nb" (Norwegian Bokmål) for "no".
        g.html_lang = "nb" if g.lang == "no" else "en"

    app.jinja_env.globals.update(t=t, tr=tr, current_language=current_language, format_date=format_date,
                                 format_datetime=format_datetime)
